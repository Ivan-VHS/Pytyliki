static int equal_utf8(const char *a, const char *b) {
    return a != NULL && b != NULL && strcmp(a, b) == 0;
}

size_t pl_mtte_catalog(const pl_mtte_layer **out) {
    if (out == NULL) return 0u;
    *out = layers;
    return PL_MTTE_LAYER_COUNT;
}

int pl_mtte_get(unsigned id, const pl_mtte_layer **out) {
    if (out == NULL || id == 0u || id > PL_MTTE_LAYER_COUNT) return -1;
    *out = &layers[id - 1u];
    return 0;
}

int pl_mtte_find(const char *name, const pl_mtte_layer **out) {
    size_t i;
    if (name == NULL || name[0] == '\0' || out == NULL) return -1;
    for (i = 0u; i < PL_MTTE_LAYER_COUNT; ++i) {
        if (equal_utf8(name, layers[i].concept) ||
            equal_utf8(name, layers[i].function) ||
            equal_utf8(name, layers[i].mechanical_operation)) {
            *out = &layers[i];
            return 0;
        }
    }
    return -2;
}

int pl_mtte_clock_init(pl_mtte_clock *clock, uint64_t period_ns) {
    if (clock == NULL || period_ns == 0u || period_ns > PL_MTTE_MAX_PERIOD_NS)
        return -1;
    clock->tick_count = 0u;
    clock->period_ns = period_ns;
    clock->elapsed_ns = 0u;
    return 0;
}

int pl_mtte_clock_advance(pl_mtte_clock *clock, uint64_t ticks) {
    if (clock == NULL || clock->period_ns == 0u ||
        clock->period_ns > PL_MTTE_MAX_PERIOD_NS) return -1;
    if (ticks > UINT64_MAX - clock->tick_count ||
        ticks > (UINT64_MAX - clock->elapsed_ns) / clock->period_ns) return -2;
    clock->tick_count += ticks;
    clock->elapsed_ns += ticks * clock->period_ns;
    return 0;
}

int pl_mtte_clock_reset(pl_mtte_clock *clock) {
    if (clock == NULL || clock->period_ns == 0u ||
        clock->period_ns > PL_MTTE_MAX_PERIOD_NS) return -1;
    clock->tick_count = 0u;
    clock->elapsed_ns = 0u;
    return 0;
}
