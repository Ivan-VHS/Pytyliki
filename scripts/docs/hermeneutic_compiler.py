#!/usr/bin/env python3
"""Generate a factual repository-state document from project files and telemetry."""
from __future__ import annotations
import argparse
import json
import re
from pathlib import Path

EXCLUDED = {".git", "build", ".venv", "__pycache__"}
SUFFIXES = {".c", ".h", ".py", ".yml", ".yaml", ".md", ".txt"}

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--src-root", default=".")
    parser.add_argument("--telemetry")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    root = Path(args.src_root).resolve()
    files = sorted(
        p.relative_to(root).as_posix() for p in root.rglob("*")
        if p.is_file() and p.suffix.lower() in SUFFIXES
        and not any(part in EXCLUDED for part in p.parts)
        and ".git" not in p.parts
    )
    header = root / "src" / "core.h"
    api = re.findall(r"^int\s+(pl_[A-Za-z0-9_]+)\s*\(",
                     header.read_text(encoding="utf-8"), flags=re.MULTILINE) if header.exists() else []
    telemetry = {}
    if args.telemetry and Path(args.telemetry).exists():
        telemetry = json.loads(Path(args.telemetry).read_text(encoding="utf-8"))
    failed = sum(telemetry.get("failed_checks", {}).values())
    lines = [
        "<!-- Generated by scripts/docs/hermeneutic_compiler.py; do not edit by hand. -->",
        "# Repository state", "",
        "Generated deterministically from the source tree and observed CI telemetry.",
        "This page reports facts only; it does not infer missing test coverage or formal proofs.", "",
        "## Snapshot", "",
        "- Project version: 0.4.0",
        "- Source/documentation files observed: {}".format(len(files)),
        "- Core API declarations extracted: {}".format(len(api)),
        "- CI telemetry records: {}".format(telemetry.get("records", 0)),
        "- Failed checks in telemetry: {}".format(failed),
        "- Telemetry SHA-256: {}".format(telemetry.get("digest_sha256", "not supplied")), "",
        "## Core API", ""
    ]
    lines.extend("- {}()".format(name) for name in api)
    if not api:
        lines.append("- No declarations extracted.")
    lines.extend(["", "## Repository files", ""])
    lines.extend("- {}".format(name) for name in files)
    lines.extend([
        "", "## Evidence boundary", "",
        "File names and public API declarations are extracted from the repository.",
        "CI counts are included only when a telemetry summary is supplied.",
        "No coverage percentage, complexity score, SMT proof, fuzzing result, or",
        "maintainability index is invented when that measurement is unavailable."
    ])
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Repository state written: {}".format(output))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
